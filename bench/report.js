/**
 * Turns the benchmark results into what the docs and the README show:
 * - SVG charts in docs/public/benchmarks/ (served by the docs site and
 *   embedded by the README, where no script can render the interactive
 *   charts of the docs);
 * - the tables between `<!-- bench:<name>:start -->` and `:end -->` markers
 *   in README.md and docs/guide/benchmarks.md (the docs pages render the same
 *   models interactively above them).
 * Both come from bench/report/model.mjs, so a chart and its table cannot
 * disagree. Text outside the markers is never touched.
 *
 * The inputs: bench/results/compare.json (pnpm bench:compare),
 * bench/results/size.json (pnpm size:compare --json),
 * bench/results/releases.json (node bench/releases.js) and
 * bench/baseline.json (pnpm bench --save).
 *
 * Run: pnpm bench:report
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const RESULTS = path.join(__dirname, 'results');
const SVG_DIR = path.join(ROOT, 'docs', 'public', 'benchmarks');
const IMAGE_BASE = 'https://metaschema.vercel.app/benchmarks';
const TARGETS = {
  readme: path.join(ROOT, 'README.md'),
  docs: path.join(ROOT, 'docs', 'guide', 'benchmarks.md'),
};
const HEADLINE = 'nested-parseStrict';
const HEADLINE_RELEASE = 'nested-valid';
const GENERATED =
  '<!-- generated by `pnpm bench:report` from bench/results — edit the results, not this block -->';

const readJson = (file) => {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    console.warn(`${path.relative(ROOT, file)} not found, skipping its charts and tables`);
    return null;
  }
};

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;
const ms = (value) => `${value.toFixed(1)} ms`;

const table = (header, align, rows) =>
  [
    `| ${header.join(' | ')} |`,
    `| ${align.join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');

// The name on the first line, the timed API and the version underneath (the
// HTML renders on GitHub, npm and VitePress).
const libraryCell = (library) => {
  const own = library.package === '@alexify/metaschema';
  const name = own ? `**${library.name}**` : library.name;
  return `${name}<br><sub>${library.variant} · v${library.version}</sub>`;
};

const image = (file, alt) =>
  `<img src="${IMAGE_BASE}/${file}" alt="${alt.replace(/"/g, '&quot;')}" width="760" />`;

const details = (summary, items) =>
  [`<details>\n<summary>${summary}</summary>`, ...items, '</details>'].join('\n\n');

const main = async () => {
  const model = await import('./report/model.mjs');
  const { renderSvg } = await import('./report/svg.mjs');
  const compare = readJson(path.join(RESULTS, 'compare.json'));
  const size = readJson(path.join(RESULTS, 'size.json'));
  const releases = readJson(path.join(RESULTS, 'releases.json'));
  const baseline = readJson(path.join(__dirname, 'baseline.json'));

  fs.mkdirSync(SVG_DIR, { recursive: true });
  const writeSvg = (file, chart, caption) => {
    fs.writeFileSync(path.join(SVG_DIR, file), renderSvg(chart, { caption }));
    console.log(`wrote docs/public/benchmarks/${file}`);
  };

  // name → { readme, docs } markdown
  const regions = {};

  if (compare) {
    const caption = model.compareCaption(compare);
    let headline = '';
    const more = [];
    for (const scenario of model.compareScenarios(compare)) {
      const chart = model.compareModel(compare, scenario.id, 'log');
      writeSvg(`compare-${scenario.id}.svg`, chart, caption);
      const img = image(`compare-${scenario.id}.svg`, `${chart.title}: ${chart.subtitle}`);
      if (scenario.id === HEADLINE) headline = img;
      else more.push(img);
    }
    const scenarios = compare.scenarios;
    const matrix = table(
      [
        'Library',
        ...scenarios.map((scenario) => `${scenario.title}<br><sub>${scenario.unit}</sub>`),
      ],
      ['---', ...scenarios.map(() => '---:')],
      compare.libraries.map((library) => [
        libraryCell(library),
        ...scenarios.map((scenario) => {
          const result = scenario.results[library.id];
          return result ? model.approx(result.median) : '—';
        }),
      ]),
    );
    const note =
      `_${caption}. Medians, rounded to three significant figures; — where the library ` +
      'cannot express the mode._';
    const titles = scenarios.filter((scenario) => scenario.id !== HEADLINE).length;
    regions.compare = {
      readme: [headline, details(`${titles} more scenarios`, more), matrix, note].join('\n\n'),
      docs: [matrix, note].join('\n\n'),
    };

    const cold = model.coldStartModel(compare);
    writeSvg('coldstart.svg', cold, model.machineCaption(compare.machine));
    const coldTable = table(
      ['Library', 'Load', 'Build', 'First check', 'Total'],
      ['---', '---:', '---:', '---:', '---:'],
      model.allRows(cold).map((row) => {
        const phases = compare.coldStart[row.id];
        const library = compare.libraries.find((candidate) => candidate.id === row.id);
        return [
          libraryCell(library),
          ms(phases.load),
          ms(phases.build),
          ms(phases.firstCheck),
          ms(phases.total),
        ];
      }),
    );
    regions.coldstart = {
      readme: [image('coldstart.svg', `${cold.title}: ${cold.subtitle}`), coldTable].join('\n\n'),
      docs: coldTable,
    };
  }

  if (size) {
    const chart = model.sizeModel(size);
    writeSvg('size.svg', chart, null);
    const sizeTable = table(
      ['Library', 'min', 'min+gzip', ''],
      ['---', '---:', '---:', '---'],
      model.allRows(chart).map((row) => {
        const library = size.libraries.find((candidate) => candidate.id === row.id);
        return [libraryCell(library), kb(library.min), kb(library.gzip), library.note ?? ''];
      }),
    );
    regions.size = {
      readme: [image('size.svg', `${chart.title}: ${chart.subtitle}`), sizeTable].join('\n\n'),
      docs: sizeTable,
    };
  }

  if (releases) {
    const caption = model.releasesCaption(releases);
    const speedup = model.speedupModel(releases);
    writeSvg('speedup.svg', speedup, caption);
    let headline = '';
    const more = [];
    for (const scenario of model.releaseScenarios(releases)) {
      const chart = model.releaseModel(releases, scenario.id);
      writeSvg(`releases-${scenario.id}.svg`, chart, caption);
      const img = image(`releases-${scenario.id}.svg`, `${chart.title}: ${chart.subtitle}`);
      if (scenario.id === HEADLINE_RELEASE) headline = img;
      else more.push(img);
    }
    const list = model.releaseList(releases);
    const releaseTable = table(
      [
        'Scenario',
        ...list.map((entry) => {
          const name =
            entry.name === 'Metarhia metaschema' ? `Metarhia ${entry.version}` : entry.version;
          return entry.backend === 'jit' ? `${name}<br><sub>JIT</sub>` : name;
        }),
      ],
      ['---', ...list.map(() => '---:')],
      releases.scenarios.map((scenario) => [
        scenario.title,
        ...list.map((entry) => {
          const result = entry.results[scenario.id];
          return result ? model.approx(result.median) : '—';
        }),
      ]),
    );
    const note = `_${caption}. ops/s (schemas/s for \`Schema.from\`), medians._`;
    const img = image('speedup.svg', `${speedup.title}: ${speedup.subtitle}`);
    regions.releases = {
      readme: [
        img,
        details('Every release, scenario by scenario', [headline, ...more]),
        releaseTable,
        note,
      ].join('\n\n'),
      docs: [releaseTable, note].join('\n\n'),
    };
  }

  if (baseline) {
    const chart = model.engineModel(baseline);
    const machine = `Node ${baseline.node} · ${baseline.date.slice(0, 10)}`;
    writeSvg('engine.svg', chart, `pnpm bench, bench/baseline.json · ${machine}`);
    regions.engine = { readme: image('engine.svg', `${chart.title}: ${chart.subtitle}`) };
  }

  for (const [target, file] of Object.entries(TARGETS)) {
    let text = fs.readFileSync(file, 'utf8');
    let touched = false;
    for (const [name, content] of Object.entries(regions)) {
      const start = `<!-- bench:${name}:start -->`;
      const end = `<!-- bench:${name}:end -->`;
      const from = text.indexOf(start);
      const to = text.indexOf(end);
      if (from === -1 || to === -1 || content[target] === undefined) continue;
      text = `${text.slice(0, from + start.length)}\n${GENERATED}\n\n${content[target]}\n\n${text.slice(to)}`;
      touched = true;
    }
    if (!touched) continue;
    fs.writeFileSync(file, text);
    console.log(`updated ${path.relative(ROOT, file)}`);
  }
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
